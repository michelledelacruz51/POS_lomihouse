begin;

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    category text not null,
    price numeric(10,2) not null default 0,
    recipe jsonb not null default '{}'::jsonb
);

create table if not exists public.inventory (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    item_name text not null,
    stock numeric(12,2) not null default 0
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_number text not null,
    order_type text not null default 'Dine-In',
    status text not null default 'New',
    total numeric(10,2) not null default 0,
    delivery_fee numeric(10,2),
    table_number text,
    delivery_channel text,
    delivery_order_number text,
    payment_method text,
    inventory_deducted boolean not null default false,
    unique (user_id, order_number)
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null references public.orders(id) on delete cascade,
    product_name text not null,
    category text not null default 'Other',
    price numeric(10,2) not null default 0,
    quantity integer not null default 1,
    total numeric(10,2) not null default 0
);

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null references public.orders(id) on delete cascade,
    payment_method text not null,
    amount numeric(10,2) not null default 0,
    status text not null default 'Paid',
    paid_at timestamptz
);

create table if not exists public.kitchen_orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null unique references public.orders(id) on delete cascade,
    status text not null default 'New',
    started_at timestamptz,
    ready_at timestamptz,
    completed_at timestamptz
);

create table if not exists public.staff (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    role text not null,
    email text
);

alter table public.products
    add column if not exists recipe jsonb not null default '{}'::jsonb;

alter table public.inventory
    add column if not exists item_name text,
    add column if not exists stock numeric(12,2) not null default 0;

alter table public.orders
    add column if not exists delivery_fee numeric(10,2),
    add column if not exists inventory_deducted boolean not null default false;

alter table public.order_items
    add column if not exists category text,
    add column if not exists total numeric(10,2);

alter table public.payments
    add column if not exists paid_at timestamptz;

alter table public.kitchen_orders
    add column if not exists started_at timestamptz,
    add column if not exists ready_at timestamptz,
    add column if not exists completed_at timestamptz;

alter table public.staff
    add column if not exists email text;

do $$
begin
    if to_regclass('public.pos_user_data') is not null then
        insert into public.products (user_id, name, category, price, recipe)
        select d.user_id,
               coalesce(nullif(item->>'name', ''), 'Unnamed product'),
               coalesce(nullif(item->>'category', ''), 'Other'),
               coalesce(nullif(item->>'price', '')::numeric, 0),
               coalesce(item->'recipe', '{}'::jsonb)
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        where d.data_key = 'foodHubProducts'
          and not exists (
              select 1 from public.products p
              where p.user_id = d.user_id
                and lower(p.name) = lower(coalesce(nullif(item->>'name', ''), 'Unnamed product'))
          );

        insert into public.inventory (user_id, item_name, stock)
        select d.user_id,
               coalesce(nullif(item->>'item_name', ''), nullif(item->>'name', ''), 'Unnamed item'),
               coalesce(nullif(item->>'stock', '')::numeric, 0)
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        where d.data_key = 'foodHubInventory'
          and not exists (
              select 1 from public.inventory i
              where i.user_id = d.user_id
                and lower(i.item_name) = lower(coalesce(
                    nullif(item->>'item_name', ''),
                    nullif(item->>'name', ''),
                    'Unnamed item'
                ))
          );

        insert into public.orders (
            user_id, order_number, order_type, status, total, delivery_fee,
            table_number, delivery_channel, delivery_order_number, payment_method
        )
        select d.user_id,
               coalesce(
                   nullif(item->>'order_number', ''),
                   nullif(ltrim(item->>'id', '#'), ''),
                   'legacy-' || md5(item::text)
               ),
               coalesce(nullif(item->>'order_type', ''), nullif(item->>'type', ''), 'Dine-In'),
               coalesce(nullif(item->>'status', ''), 'New'),
               coalesce(nullif(item->>'total', '')::numeric, 0),
               nullif(coalesce(item->>'delivery_fee', item->>'deliveryFee'), '')::numeric,
               coalesce(nullif(item->>'table_number', ''), nullif(item->>'table', '')),
               coalesce(nullif(item->>'delivery_channel', ''), nullif(item->>'deliveryChannel', '')),
               coalesce(nullif(item->>'delivery_order_number', ''), nullif(item->>'deliveryOrderNumber', '')),
               coalesce(nullif(item->>'payment_method', ''), nullif(item->>'paymentMethod', ''))
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        where d.data_key = 'foodHubOrders'
          and not exists (
              select 1 from public.orders o
              where o.user_id = d.user_id
                and o.order_number = coalesce(
                    nullif(item->>'order_number', ''),
                    nullif(ltrim(item->>'id', '#'), ''),
                    'legacy-' || md5(item::text)
                )
          );

        insert into public.order_items (
            user_id, order_id, product_name, category, price, quantity, total
        )
        select d.user_id,
               o.id,
               coalesce(nullif(line->>'product_name', ''), nullif(line->>'name', ''), 'Unnamed product'),
               coalesce(nullif(line->>'category', ''), 'Other'),
               coalesce(nullif(coalesce(line->>'price', line->>'unit_price'), '')::numeric, 0),
               greatest(coalesce(nullif(line->>'quantity', '')::integer, 1), 1),
               coalesce(
                   nullif(coalesce(line->>'total', line->>'subtotal'), '')::numeric,
                   coalesce(nullif(coalesce(line->>'price', line->>'unit_price'), '')::numeric, 0)
                       * greatest(coalesce(nullif(line->>'quantity', '')::integer, 1), 1)
               )
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) legacy_order
        cross join lateral jsonb_array_elements(
            case
                when jsonb_typeof(legacy_order->'items') = 'array' then legacy_order->'items'
                else '[]'::jsonb
            end
        ) line
        join public.orders o
          on o.user_id = d.user_id
         and o.order_number = coalesce(
             nullif(legacy_order->>'order_number', ''),
             nullif(ltrim(legacy_order->>'id', '#'), ''),
             'legacy-' || md5(legacy_order::text)
         )
        where d.data_key = 'foodHubOrders'
          and not exists (
              select 1 from public.order_items oi
              where oi.order_id = o.id
                and oi.product_name = coalesce(nullif(line->>'product_name', ''), nullif(line->>'name', ''), 'Unnamed product')
                and oi.price = coalesce(nullif(coalesce(line->>'price', line->>'unit_price'), '')::numeric, 0)
                and oi.quantity = greatest(coalesce(nullif(line->>'quantity', '')::integer, 1), 1)
          );

        insert into public.payments (user_id, order_id, payment_method, amount, status, paid_at)
        select d.user_id,
               o.id,
               coalesce(nullif(item->>'payment_method', ''), nullif(item->>'paymentMethod', '')),
               coalesce(nullif(item->>'total', '')::numeric, 0),
               coalesce(nullif(item->>'payment_status', ''), nullif(item->>'paymentStatus', ''), 'Paid'),
               case
                   when coalesce(item->>'payment_status', item->>'paymentStatus', 'Paid') = 'Paid'
                   then nullif(coalesce(item->>'paid_at', item->>'createdAt'), '')::timestamptz
                   else null
               end
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        join public.orders o
          on o.user_id = d.user_id
         and o.order_number = coalesce(
             nullif(item->>'order_number', ''),
             nullif(ltrim(item->>'id', '#'), ''),
             'legacy-' || md5(item::text)
         )
        where d.data_key = 'foodHubOrders'
          and coalesce(nullif(item->>'payment_method', ''), nullif(item->>'paymentMethod', '')) is not null
          and not exists (
              select 1 from public.payments p where p.order_id = o.id
          );

        insert into public.kitchen_orders (
            user_id, order_id, status, started_at, ready_at, completed_at
        )
        select d.user_id,
               o.id,
               coalesce(nullif(item->>'status', ''), 'New'),
               nullif(coalesce(item->>'started_at', item->>'startedAt'), '')::timestamptz,
               nullif(coalesce(item->>'ready_at', item->>'readyAt'), '')::timestamptz,
               nullif(coalesce(item->>'completed_at', item->>'completedAt'), '')::timestamptz
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        join public.orders o
          on o.user_id = d.user_id
         and o.order_number = coalesce(
             nullif(item->>'order_number', ''),
             nullif(ltrim(item->>'id', '#'), ''),
             'legacy-' || md5(item::text)
         )
        where d.data_key = 'foodHubKitchenOrders'
          and not exists (
              select 1 from public.kitchen_orders k where k.order_id = o.id
          );

        insert into public.staff (user_id, name, role, email)
        select d.user_id,
               coalesce(nullif(item->>'name', ''), 'Unnamed staff'),
               coalesce(nullif(item->>'role', ''), 'Staff'),
               case
                   when coalesce(item->>'email', item->>'contact', '') ~* '^[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}$'
                   then coalesce(item->>'email', item->>'contact')
                   else null
               end
        from public.pos_user_data d
        cross join lateral jsonb_array_elements(
            case when jsonb_typeof(d.data) = 'array' then d.data else '[]'::jsonb end
        ) item
        where d.data_key = 'foodHubStaff'
          and not exists (
              select 1 from public.staff s
              where s.user_id = d.user_id
                and lower(s.name) = lower(coalesce(nullif(item->>'name', ''), 'Unnamed staff'))
                and s.role = coalesce(nullif(item->>'role', ''), 'Staff')
          );
    end if;
end
$$;

do $$
begin
    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'order_items'
          and column_name = 'unit_price'
    ) then
        execute '
            update public.order_items
            set price = coalesce(unit_price, price)
        ';
    end if;

    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'order_items'
          and column_name = 'product_id'
    ) then
        execute '
            update public.order_items oi
            set category = coalesce(
                nullif(oi.category, ''''),
                (select p.category from public.products p where p.id = oi.product_id),
                ''Other''
            )
        ';
    else
        update public.order_items
        set category = coalesce(nullif(category, ''), 'Other');
    end if;

    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'order_items'
          and column_name = 'subtotal'
    ) then
        execute '
            update public.order_items
            set total = coalesce(subtotal, price * quantity)
        ';
    else
        update public.order_items
        set total = price * quantity;
    end if;

    if exists (
        select 1
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'kitchen_orders'
          and column_name = 'preparing_at'
    ) then
        execute '
            update public.kitchen_orders
            set started_at = coalesce(started_at, preparing_at)
        ';
    end if;
end
$$;

