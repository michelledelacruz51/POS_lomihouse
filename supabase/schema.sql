-- Edwin's Lomi House POS database schema.
-- Private ownership and relationship columns are required by the app and RLS.

create table if not exists public.products (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    category text not null,
    price numeric(10,2) not null default 0 check (price >= 0),
    recipe jsonb not null default '{}'::jsonb
);

create table if not exists public.inventory (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    item_name text not null,
    stock numeric(12,2) not null default 0 check (stock >= 0)
);

create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_number text not null,
    order_type text not null default 'Dine-In',
    status text not null default 'New',
    total numeric(10,2) not null default 0 check (total >= 0),
    delivery_fee numeric(10,2) check (delivery_fee is null or delivery_fee >= 0),
    table_number text,
    delivery_channel text,
    delivery_order_number text,
    payment_method text,
    inventory_deducted boolean not null default false,
    unique (user_id, order_number)
);

create table if not exists public.order_items (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null references public.orders(id) on delete cascade,
    product_name text not null,
    category text not null default 'Other',
    price numeric(10,2) not null default 0 check (price >= 0),
    quantity integer not null default 1 check (quantity > 0),
    total numeric(10,2) not null default 0 check (total >= 0)
);

create table if not exists public.payments (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null references public.orders(id) on delete cascade,
    payment_method text not null,
    amount numeric(10,2) not null default 0 check (amount >= 0),
    status text not null default 'Paid',
    paid_at timestamptz
);

create table if not exists public.kitchen_orders (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    order_id bigint not null unique references public.orders(id) on delete cascade,
    status text not null default 'New',
    started_at timestamptz,
    ready_at timestamptz,
    completed_at timestamptz
);

create table if not exists public.staff (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null,
    role text not null,
    email text
);

create or replace function public.set_kitchen_order_times()
returns trigger
language plpgsql
as $$
begin
    if new.status = 'Preparing' then
        new.started_at := coalesce(new.started_at, now());
    elsif new.status in ('Ready', 'Ready for Pickup', 'Ready for Dispatch') then
        new.ready_at := coalesce(new.ready_at, now());
    elsif new.status in ('Completed', 'Delivered') then
        new.completed_at := coalesce(new.completed_at, now());
    end if;

    return new;
end;
$$;

drop trigger if exists kitchen_order_status_times on public.kitchen_orders;
create trigger kitchen_order_status_times
before insert or update of status on public.kitchen_orders
for each row
execute function public.set_kitchen_order_times();

alter table public.products enable row level security;
alter table public.inventory enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.payments enable row level security;
alter table public.kitchen_orders enable row level security;
alter table public.staff enable row level security;

drop policy if exists "Users can manage their own products" on public.products;
create policy "Users can manage their own products"
on public.products for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can manage their own inventory" on public.inventory;
create policy "Users can manage their own inventory"
on public.inventory for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can manage their own orders" on public.orders;
create policy "Users can manage their own orders"
on public.orders for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can manage their own order items" on public.order_items;
create policy "Users can manage their own order items"
on public.order_items for all to authenticated
using (
    auth.uid() = user_id
    and exists (
        select 1
        from public.orders
        where orders.id = order_items.order_id
          and orders.user_id = auth.uid()
    )
)
with check (
    auth.uid() = user_id
    and exists (
        select 1
        from public.orders
        where orders.id = order_items.order_id
          and orders.user_id = auth.uid()
    )
);

drop policy if exists "Users can manage their own payments" on public.payments;
create policy "Users can manage their own payments"
on public.payments for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can manage their own kitchen orders" on public.kitchen_orders;
create policy "Users can manage their own kitchen orders"
on public.kitchen_orders for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can manage their own staff" on public.staff;
create policy "Users can manage their own staff"
on public.staff for all to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

grant select, insert, update, delete
on public.products,
   public.inventory,
   public.orders,
   public.order_items,
   public.payments,
   public.kitchen_orders,
   public.staff
to authenticated;

grant usage, select on all sequences in schema public to authenticated;
